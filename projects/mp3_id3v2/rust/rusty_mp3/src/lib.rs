use std::error::Error;
use std::fs::File;
use std::path::Path;

fn parse_package(package: &str, path: &Path) -> Result<serde_json::Value, Box<dyn Error>> {
    let result = match package {
        "rusty_mp3" => {
            let bytes = std::fs::read(path)?;
            let mut decoder = rusty_mp3::Mp3Decoder::new();
            decoder.push(&bytes);
            let frame = decoder.next_frame()?;
            serde_json::json!({"sample_rate":frame.sample_rate,"channels":frame.channels,"decoded_samples":frame.samples.len()})
        }
        _ => return Err(format!("unknown package: {package}").into()),
    };
    Ok(result)
}


use std::sync::atomic::{AtomicU64, Ordering};
static NEXT_INPUT: AtomicU64 = AtomicU64::new(0);

pub fn parse(data: &[u8]) -> Result<serde_json::Value, Box<dyn Error>> {
    if data.is_empty() || data.len() > (1 << 20) {
        return Err("input outside harness limit".into());
    }
    let path = std::env::temp_dir().join(format!(
        "parsarium-rust-{}-{}.mp3",
        std::process::id(), NEXT_INPUT.fetch_add(1, Ordering::Relaxed)));
    std::fs::write(&path, data)?;
    let outcome = parse_package("rusty_mp3", &path);
    std::fs::remove_file(path)?;
    outcome
}
