"""Byte-input harness for mpl-simple-svg-parser 0.2.1 on svg."""
import tempfile
from pathlib import Path
import adapter


def parse_data(data: bytes):
    if not data or len(data) > (1 << 20):
        return None
    with tempfile.NamedTemporaryFile(suffix=".svg") as source:
        source.write(data)
        source.flush()
        return adapter.parse('mpl-simple-svg-parser', Path(source.name))


def fuzz_one_input(data: bytes):
    try:
        parse_data(data)
    except (EOFError, OSError, UnicodeError, ValueError):
        pass
