"""Build AFL++ parser-source feedback bridges for verified managed projects."""

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
from hashlib import sha256
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

from run_case import ROOT, image_for, project_for


BRIDGE = ROOT / "fuzzing/afl-bridge"
OVERLAYS = ROOT / "fuzzing/afl-native"


UBUNTU_BASE = "ubuntu@sha256:065aa8626841f16057b78b027b464cd59c4fac36c204c72dcbf48d66f5fa8a96"
AFL_PACKAGE = {"go": "4.33c-1.1ubuntu1", "java": "4.09c-1ubuntu3",
               "javascript": "4.21c-5", "php": "4.33c-1.1ubuntu1"}


def dockerfile(base_image: str, relative: Path, prefix: str,
               ecosystem: str, parse_function: str | None,
               fuzz_entry: str | None, java_environment: dict[str, str]) -> str:
    overlay = f"fuzzing/afl-native/{relative.as_posix()}"
    trace_files = ({"go": ["go_trace.py"],
                    "java": ["JavaCase.java", "java_trace.py"],
                    "javascript": ["javascript_child.js", "javascript_trace.js"],
                    "php": ["php_trace.php"]}[ecosystem])
    copies = "".join(f"COPY fuzzing/afl-bridge/{name} /work/{name if name == 'JavaCase.java' else 'afl_' + name}\n"
                     for name in trace_files)
    env_function = f"ENV PARSARIUM_PARSE_FUNCTION={parse_function}\n" if parse_function else ""
    env_entry = f"ENV PARSARIUM_FUZZ_ENTRY={fuzz_entry}\n" if fuzz_entry else ""
    env_java = "".join(f"ENV {name}={value}\n" for name, value in java_environment.items())
    image_base = UBUNTU_BASE if ecosystem == "go" else base_image
    go_binary = f"COPY --from={base_image} /work/harness.test /work/harness.test\n" if ecosystem == "go" else ""
    python_runtime = " python3" if ecosystem == "go" else ""
    java_compile = ("RUN mkdir /work/afl-java-classes && javac -d /work/afl-java-classes "
                    "/work/JavaCase.java\n") if ecosystem == "java" else ""
    return f'''# Parser-line AFL++ bridge generated by scripts/build_afl_bridge.py
FROM --platform=linux/arm64 {image_base}
RUN apt-get update -qq && apt-get install -y --no-install-recommends afl++={AFL_PACKAGE[ecosystem]} clang{python_runtime} \\
    && rm -rf /var/lib/apt/lists/*
{go_binary}COPY fuzzing/afl-bridge/afl_proxy.c /work/afl_proxy.c
{copies}COPY {overlay}/afl_trace /work/afl_trace
ENV PARSARIUM_SUBJECT_PREFIX={prefix}
{env_function}{env_entry}{env_java}{java_compile}RUN AFL_LLVM_INSTRUMENT=CLASSIC afl-clang-fast -O2 /work/afl_proxy.c -ldl -o /work/afl_proxy
ENTRYPOINT ["/work/afl_proxy"]
'''


def run(args: list[str], timeout: int = 1200) -> subprocess.CompletedProcess:
    result = subprocess.run(args, cwd=ROOT, capture_output=True, text=True, timeout=timeout)
    if result.returncode:
        raise RuntimeError(f"{' '.join(args[:8])}: {(result.stdout + result.stderr)[-3000:]}")
    return result


def build_one(relative: Path) -> dict:
    project, manifest = project_for(*relative.parts)
    ecosystem = manifest["ecosystem"]
    if ecosystem not in {"go", "java", "javascript", "php"}:
        raise ValueError("Go, Java, JavaScript, or PHP project required")
    base_image, base_image_id = image_for(project, manifest)
    verified_base = json.loads((project / "verification.json").read_text())["image_id"]
    if base_image_id != verified_base:
        raise ValueError("base project image differs from verification receipt")
    overlay = OVERLAYS / relative
    overlay.mkdir(parents=True, exist_ok=True)
    parse_function = None
    java_environment = {}
    if ecosystem == "go":
        trace_command = 'python3 /work/afl_go_trace.py'
        bridge_names = ("afl_proxy.c", "go_trace.py")
    elif ecosystem == "java":
        args = manifest["fuzz_smoke_args"]
        classpath = next(arg.removeprefix("--cp=") for arg in args if arg.startswith("--cp="))
        target = next(arg.removeprefix("--target_class=") for arg in args
                      if arg.startswith("--target_class="))
        control_script = (project / "run-control.sh").read_text()
        def extract(pattern: str) -> str:
            match = re.search(pattern, control_script)
            if not match:
                raise ValueError(f"missing Java coverage option: {pattern}")
            return match.group(1)
        java_environment = {
            "PARSARIUM_JAVA_CLASSPATH": classpath,
            "PARSARIUM_TARGET_CLASS": target,
            "PARSARIUM_JACOCO_INCLUDES": extract(r"includes=([^ ,\\]+)"),
            "PARSARIUM_PARSER_JAR": extract(r"--classfiles\s+(\S+)"),
            "PARSARIUM_PARSER_SOURCES": extract(r"--sourcefiles\s+(\S+)"),
        }
        trace_command = 'python3 /work/afl_java_trace.py'
        bridge_names = ("afl_proxy.c", "JavaCase.java", "java_trace.py")
    elif ecosystem == "javascript":
        trace_command = 'node /work/afl_javascript_trace.js'
        bridge_names = ("afl_proxy.c", "javascript_child.js", "javascript_trace.js")
    else:
        functions = set(re.findall(r"parsarium_parse_[a-z0-9_]+",
                                   (project / "fuzz-target.php").read_text()))
        if len(functions) != 1:
            raise ValueError("PHP fuzz target has no unique parser entry")
        parse_function = functions.pop()
        trace_command = 'php -d xdebug.mode=coverage /work/afl_php_trace.php'
        bridge_names = ("afl_proxy.c", "php_trace.php")
    (overlay / "afl_trace").write_text(
        f'#!/bin/sh\nexec {trace_command} "$1" "$2"\n'
    )
    (overlay / "Dockerfile").write_text(
        dockerfile(base_image, relative, manifest["coverage_subject_prefix"],
                   ecosystem, parse_function, manifest.get("fuzz_entry"), java_environment)
    )
    image = f"parsarium-afl/{relative.parts[0]}-{ecosystem}-{relative.parts[2]}:local"
    print(f"Building {image}", flush=True)
    run(["docker", "build", "--quiet", "--platform", manifest["platform"],
         "-f", str(overlay / "Dockerfile"), "-t", image, str(ROOT)])
    image_id = run(["docker", "image", "inspect", image, "--format", "{{.Id}}"]).stdout.strip()
    version = run(["docker", "run", "--rm", "--platform", manifest["platform"],
                   "--entrypoint", "dpkg-query", image, "-W", "-f=${Version}", "afl++"]).stdout.strip()
    if version != AFL_PACKAGE[ecosystem]:
        raise RuntimeError(f"AFL++ package version changed: {version} != {AFL_PACKAGE[ecosystem]}")
    control = ROOT / manifest["control"]
    with tempfile.TemporaryDirectory(prefix="parsarium-afl-bridge-") as temp:
        tracer = run(["docker", "run", "--rm", "--platform", manifest["platform"],
                      "--network", "none", "--read-only", "--cap-drop", "ALL",
                      "--security-opt", "no-new-privileges",
                      "--user", f"{os.getuid()}:{os.getgid()}",
                      "--tmpfs", "/tmp:rw,exec,nosuid,size=64m",
                      "-v", f"{control}:/input/control:ro", "-v", f"{temp}:/coverage",
                      "--entrypoint", "/bin/sh", image,
                      "/work/afl_trace", "/input/control", "/coverage/features.txt"], 120)
        del tracer
        features = (Path(temp) / "features.txt").read_text().splitlines()
        if not features:
            raise RuntimeError("valid control did not execute parser source lines")
        run(["docker", "run", "--rm", "--platform", manifest["platform"],
             "--network", "none", "--read-only", "--cap-drop", "ALL",
             "--security-opt", "no-new-privileges",
             "--user", f"{os.getuid()}:{os.getgid()}",
             "--tmpfs", "/tmp:rw,exec,nosuid,size=64m",
             "-e", "AFL_MAP_SIZE=65536", "-v", f"{control}:/input/control:ro",
             "-v", f"{temp}:/coverage", "--entrypoint", "afl-showmap", image,
             "-m", "none", "-t", "10000", "-o", "/coverage/edges.txt", "--",
             "/work/afl_proxy", "/input/control"], 120)
        edges = (Path(temp) / "edges.txt").read_text().splitlines()
        if len(edges) < 2:
            raise RuntimeError("AFL++ did not report parser feedback")
    receipt = {
        "schema_version": 1, "project": str(relative), "pass": True,
        "feedback_kind": f"{ecosystem}_parser_source_{'ranges' if ecosystem == 'javascript' else 'blocks' if ecosystem == 'go' else 'lines'}_to_afl_bitmap",
        "base_project_receipt_sha256": sha256((project / "verification.json").read_bytes()).hexdigest(),
        "base_image_id": base_image_id, "image_id": image_id, "platform": manifest["platform"],
        "control_sha256": manifest["control_sha256"],
        "parser_source_features": len(features), "feedback_edges": len(edges),
        "afl_map_size": 65536, "afl_package": version,
        "overlay_file_sha256": {
            name: sha256((overlay / name).read_bytes()).hexdigest()
            for name in ("Dockerfile", "afl_trace")
        },
        "bridge_file_sha256": {
            name: sha256((BRIDGE / name).read_bytes()).hexdigest()
            for name in bridge_names
        },
    }
    (overlay / "verification.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(f"Verified {relative}: {len(features)} parser features, {len(edges)} AFL++ tuples", flush=True)
    return receipt


def main() -> None:
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("format", nargs="?")
    cli.add_argument("ecosystem", nargs="?")
    cli.add_argument("slug", nargs="?")
    cli.add_argument("--all", action="store_true")
    cli.add_argument("--workers", type=int, default=2)
    args = cli.parse_args()
    if args.all:
        projects = sorted(path.parent.relative_to(ROOT / "projects")
                          for ecosystem in ("go", "java", "javascript", "php")
                          for path in (ROOT / "projects").glob(f"*/{ecosystem}/*/manifest.json"))
    elif args.format and args.ecosystem in {"go", "java", "javascript", "php"} and args.slug:
        projects = [Path(args.format) / args.ecosystem / args.slug]
    else:
        cli.error("provide FORMAT go|java|javascript|php SLUG or --all")
    results = []
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures = {pool.submit(build_one, relative): relative for relative in projects}
        for future in as_completed(futures):
            relative = futures[future]
            try:
                results.append(future.result())
            except Exception as exc:
                print(f"FAILED {relative}: {exc}", flush=True)
                results.append({"project": str(relative), "pass": False, "error": str(exc)})
    if args.all:
        report = {"schema_version": 1, "checked_at_utc": datetime.now(timezone.utc).isoformat(),
                  "projects_total": len(results),
                  "projects_verified": sum(item["pass"] for item in results),
                  "results": sorted(results, key=lambda item: item["project"])}
        (ROOT / "data/afl-bridge-smoke.json").write_text(json.dumps(report, indent=2) + "\n")
    if not all(item["pass"] for item in results):
        raise SystemExit(1)


if __name__ == "__main__":
    main()
