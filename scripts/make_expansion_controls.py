#!/usr/bin/env python3
"""Write the small valid controls for the JSON/XML/plain-MP3 expansion inventory.

The JSON, XML and silent MP3 controls are generated byte-for-byte from this
script. The tone MP3 is encoded by the recorded LAME build when --tone is given.
"""
import hashlib, json, math, struct, subprocess, sys, wave
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "data/expansion/controls"

JSON = ('{"format":"json","items":[1,2.5,-3e2,true,false,null],'
        '"nested":{"text":"caf\\u00e9 \\u2713","empty":[]},"count":3}\n').encode()

XML = ('<?xml version="1.0" encoding="UTF-8"?>\n'
       '<catalog xmlns="urn:parsarium:control" version="1">'
       '<item id="a">caf&#233;</item>'
       '<item id="b"><![CDATA[x<y]]></item>'
       '<!-- comment --><empty/></catalog>\n').encode()

# MPEG-1 Layer III, no CRC, 128 kbit/s, 44100 Hz, mono, no padding.
# Frame length = 144 * 128000 / 44100 = 417 bytes. All-zero side info and
# main data decode to silence. No ID3v1/ID3v2/APE tag and no Xing/Info frame.
HEADER = bytes([0xFF, 0xFB, 0x90, 0xC0])
FRAMES = 38
SILENT = (HEADER + bytes(413)) * FRAMES


def tone():
    wav = OUT / "tone-16k-mono.wav.tmp"
    with wave.open(str(wav), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(16000)
        w.writeframes(b"".join(struct.pack("<h", int(12000 * math.sin(2 * math.pi * 440 * i / 16000))) for i in range(16000)))
    out = OUT / "tone-plain-16k.mp3"
    # -t: no Xing/Info frame; no tag options, so LAME writes no ID3 tag.
    subprocess.run(["lame", "--quiet", "-t", "--noreplaygain", "-m", "m", "-b", "32", str(wav), str(out)], check=True)
    wav.unlink()
    ver = subprocess.run(["lame", "--version"], capture_output=True, text=True).stdout.splitlines()[0]
    return out, ver


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "control.json").write_bytes(JSON)
    (OUT / "control.xml").write_bytes(XML)
    (OUT / "silent-plain-44k.mp3").write_bytes(SILENT)
    if "--tone" in sys.argv:
        out, ver = tone()
        (OUT / "tone-plain-16k.encoder.txt").write_text(ver + "\n")
    for p in sorted(OUT.iterdir()):
        if p.suffix in {".json", ".xml", ".mp3"} and p.name != "manifest.json":
            print(p.name, len(p.read_bytes()), hashlib.sha256(p.read_bytes()).hexdigest())


if __name__ == "__main__":
    main()
