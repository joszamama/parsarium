"""Build AFL++ parser-line feedback bridges for verified Python projects."""

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
from hashlib import sha256
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

from run_case import ROOT, image_for, project_for
from docker_slots import docker_build_slot


BRIDGE = ROOT / "fuzzing/afl-bridge"
OVERLAYS = ROOT / "fuzzing/afl-native"
AFL_UBUNTU = "4.33c-1.1ubuntu1"
AFL_DEBIAN_STDLIB = "4.04c-4"


def dockerfile(base_image: str, platform: str, relative: Path, prefix: str,
               afl_package: str, native_module_glob: str | None = None,
               feature_only_proxy: bool = False) -> str:
    overlay = f"fuzzing/afl-native/{relative.as_posix()}"
    tracer = "python_llvm_native_trace.py" if native_module_glob else "python_trace.py"
    native_env = f"ENV PARSARIUM_LLVM_MODULE_GLOB={native_module_glob}\n" if native_module_glob else ""
    proxy_source = f"{overlay}/afl_proxy.c" if feature_only_proxy else "fuzzing/afl-bridge/afl_proxy.c"
    tracer_source = f"{overlay}/afl_python_trace.py" if feature_only_proxy else f"fuzzing/afl-bridge/{tracer}"
    start_copy = f"COPY {overlay}/afl_start.c /work/afl_start.c\n" if feature_only_proxy else ""
    # In this opt-in mode only the AFL runtime anchor is instrumented; the proxy loop adds no noisy edges.
    compile_proxy = (
        "RUN clang -O2 -c /work/afl_proxy.c -o /work/afl_proxy.o "
        "&& AFL_LLVM_INSTRUMENT=CLASSIC afl-clang-fast -O0 -c /work/afl_start.c -o /work/afl_start.o "
        "&& AFL_LLVM_INSTRUMENT=CLASSIC afl-clang-fast /work/afl_proxy.o /work/afl_start.o -ldl -o /work/afl_proxy"
        if feature_only_proxy else
        "RUN AFL_LLVM_INSTRUMENT=CLASSIC afl-clang-fast -O2 /work/afl_proxy.c -ldl -o /work/afl_proxy")
    return f'''# Python parser-line AFL++ bridge generated by scripts/build_afl_python.py
FROM --platform={platform} {base_image}
RUN apt-get update -qq && apt-get install -y --no-install-recommends afl++={afl_package} clang \\
    && rm -rf /var/lib/apt/lists/*
COPY {proxy_source} /work/afl_proxy.c
{start_copy}COPY {tracer_source} /work/afl_python_trace.py
COPY {overlay}/afl_trace /work/afl_trace
ENV PARSARIUM_SUBJECT_PREFIX={prefix}
{native_env}
{compile_proxy}
ENTRYPOINT ["/work/afl_proxy"]
'''


def run(args: list[str], timeout: int = 1200) -> subprocess.CompletedProcess:
    result = subprocess.run(args, cwd=ROOT, capture_output=True, text=True, timeout=timeout)
    if result.returncode:
        raise RuntimeError(f"{' '.join(args[:8])}: {(result.stdout + result.stderr)[-3000:]}")
    return result


def build_one(relative: Path) -> dict:
    project, manifest = project_for(*relative.parts)
    if manifest["ecosystem"] != "python":
        raise ValueError("Python project required")
    base_image, base_image_id = image_for(project, manifest)
    verified_base = json.loads((project / "verification.json").read_text())["image_id"]
    if base_image_id != verified_base:
        raise ValueError("base project image differs from verification receipt")
    overlay = OVERLAYS / relative
    overlay.mkdir(parents=True, exist_ok=True)
    afl_package = manifest.get("afl_package_release", AFL_DEBIAN_STDLIB if
                               manifest.get("kind") == "standard" else AFL_UBUNTU)
    if not re.fullmatch(r"[0-9][A-Za-z0-9.+:~_-]*", afl_package):
        raise ValueError("invalid AFL++ package release")
    native_module_glob = manifest.get("afl_llvm_module_glob")
    feature_only_proxy = manifest.get("afl_feature_only_proxy", False)
    trace_python = manifest.get("afl_python_entrypoint", manifest["fuzz_smoke_entrypoint"])
    (overlay / "afl_trace").write_text(
        f'#!/bin/sh\nexec {trace_python} /work/afl_python_trace.py "$1" "$2"\n'
    )
    (overlay / "Dockerfile").write_text(
        dockerfile(base_image, manifest["platform"], relative,
                   manifest.get("afl_coverage_subject_prefix", manifest["coverage_subject_prefix"]),
                   afl_package, native_module_glob, feature_only_proxy)
    )
    image = f"parsarium-afl/{relative.parts[0]}-python-{relative.parts[2]}:local"
    print(f"Building {image}", flush=True)
    with docker_build_slot():
        run(["docker", "build", "--quiet", "--platform", manifest["platform"],
             "-f", str(overlay / "Dockerfile"), "-t", image, str(ROOT)])
    image_id = run(["docker", "image", "inspect", image, "--format", "{{.Id}}"]).stdout.strip()
    version = run(["docker", "run", "--rm", "--platform", manifest["platform"],
                   "--entrypoint", "dpkg-query", image, "-W", "-f=${Version}", "afl++"]).stdout.strip()
    if version != afl_package:
        raise RuntimeError(f"AFL++ package version changed: {version} != {afl_package}")
    control = ROOT / manifest["control"]
    with tempfile.TemporaryDirectory(prefix="parsarium-afl-python-") as temp:
        tracer = run(["docker", "run", "--rm", "--platform", manifest["platform"],
                      "--network", "none", "--read-only", "--cap-drop", "ALL",
                      "--security-opt", "no-new-privileges",
                      "--user", f"{os.getuid()}:{os.getgid()}",
                      "--tmpfs", "/tmp:rw,exec,nosuid,size=64m",
                      "-v", f"{control}:/input/control:ro", "-v", f"{temp}:/coverage",
                      "--entrypoint", "/bin/sh", image,
                      "/work/afl_trace", "/input/control", "/coverage/features.txt"], 120)
        del tracer
        features = (Path(temp) / "features.txt").read_text().splitlines()
        if not features:
            raise RuntimeError("valid control did not execute parser source lines")
        run(["docker", "run", "--rm", "--platform", manifest["platform"],
             "--network", "none", "--read-only", "--cap-drop", "ALL",
             "--security-opt", "no-new-privileges",
             "--user", f"{os.getuid()}:{os.getgid()}",
             "--tmpfs", "/tmp:rw,exec,nosuid,size=64m",
             "-e", "AFL_MAP_SIZE=65536", "-v", f"{control}:/input/control:ro",
             "-v", f"{temp}:/coverage", "--entrypoint", "afl-showmap", image,
             "-m", "none", "-t", "120000", "-o", "/coverage/edges.txt", "--",
             "/work/afl_proxy", "/input/control"], 120)
        edges = (Path(temp) / "edges.txt").read_text().splitlines()
        if len(edges) < 2:
            raise RuntimeError("AFL++ did not report parser feedback")
    receipt = {
        "schema_version": 1, "project": str(relative), "pass": True,
        "feedback_kind": ("llvm_native_parser_regions_to_afl_bitmap" if native_module_glob
                          else "python_parser_source_lines_to_afl_bitmap"),
        "base_project_receipt_sha256": sha256((project / "verification.json").read_bytes()).hexdigest(),
        "base_image_id": base_image_id, "image_id": image_id, "platform": manifest["platform"],
        "control_sha256": manifest["control_sha256"],
        "parser_source_features": len(features), "feedback_edges": len(edges),
        "afl_map_size": 65536, "afl_package": version,
        "overlay_file_sha256": {
            name: sha256((overlay / name).read_bytes()).hexdigest()
            for name in (("Dockerfile", "afl_trace", "afl_proxy.c", "afl_start.c", "afl_python_trace.py")
                         if feature_only_proxy else ("Dockerfile", "afl_trace"))
        },
        "bridge_file_sha256": {
            name: sha256((BRIDGE / name).read_bytes()).hexdigest()
            for name in (() if feature_only_proxy else
                         ("afl_proxy.c", "python_llvm_native_trace.py" if native_module_glob
                          else "python_trace.py"))
        },
    }
    (overlay / "verification.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(f"Verified {relative}: {len(features)} parser lines, {len(edges)} AFL++ tuples", flush=True)
    return receipt


def main() -> None:
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("format", nargs="?")
    cli.add_argument("ecosystem", nargs="?")
    cli.add_argument("slug", nargs="?")
    cli.add_argument("--all", action="store_true")
    cli.add_argument("--workers", type=int, default=2)
    args = cli.parse_args()
    if args.all:
        projects = sorted(path.parent.relative_to(ROOT / "projects")
                          for path in (ROOT / "projects").glob("*/python/*/manifest.json"))
    elif all((args.format, args.ecosystem == "python", args.slug)):
        projects = [Path(args.format) / "python" / args.slug]
    else:
        cli.error("provide FORMAT python SLUG or --all")
    results = []
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures = {pool.submit(build_one, relative): relative for relative in projects}
        for future in as_completed(futures):
            relative = futures[future]
            try:
                results.append(future.result())
            except Exception as exc:
                print(f"FAILED {relative}: {exc}", flush=True)
                results.append({"project": str(relative), "pass": False, "error": str(exc)})
    if args.all:
        report = {"schema_version": 1, "checked_at_utc": datetime.now(timezone.utc).isoformat(),
                  "projects_total": len(results),
                  "projects_verified": sum(item["pass"] for item in results),
                  "results": sorted(results, key=lambda item: item["project"])}
        (ROOT / "data/afl-python-smoke.json").write_text(json.dumps(report, indent=2) + "\n")
    if not all(item["pass"] for item in results):
        raise SystemExit(1)


if __name__ == "__main__":
    main()
