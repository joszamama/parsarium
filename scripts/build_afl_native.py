"""Build an AFL++ overlay for a verified C or C++ parser project.

The overlay preserves the project's pinned source archive and harness. It
recompiles both parser and harness with AFL++'s compiler and driver, then uses
afl-showmap on the valid control to verify actual feedback edges. No campaign
is started.
"""

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
from hashlib import sha256
import json
import os
from pathlib import Path
import subprocess

from run_case import ROOT, project_for
from docker_slots import docker_build_slot


AFL_PACKAGE = "4.33c-1.1ubuntu1"
OVERLAYS = ROOT / "fuzzing/afl-native"
REWRITE = ('RUN python3 -c \'from pathlib import Path; p=Path("/work/build.sh"); '
           's=p.read_text(); s=s.replace("clang++","AFL_CXX")'
           '.replace("clang","afl-clang-fast")'
           '.replace("AFL_CXX","afl-clang-fast++")'
           '.replace(",undefined",",undefined -fno-sanitize=function"); p.write_text(s)\' '
           '&& chmod +x /work/build.sh && /work/build.sh \\')


def derived_dockerfile(project: Path) -> str:
    source = (project / "Dockerfile").read_text()
    marker = "RUN chmod +x /work/build.sh && /work/build.sh \\"
    if source.count(marker) != 1 or source.count("apt-get install -y --no-install-recommends") != 2:
        raise ValueError("native Dockerfile shape is not supported")
    text = source.replace("apt-get install -y --no-install-recommends",
                          f"apt-get install -y --no-install-recommends afl++={AFL_PACKAGE} python3")
    text = text.replace(marker, REWRITE)
    if project.name == "imagemagick":
        # The CLI utility is unnecessary for library harnesses and its link
        # pulls the AFL runtime into libtool more than once.
        text = text.replace(
            "&& chmod +x /work/build.sh && /work/build.sh",
            "&& sed -i 's@^make -j 4$@make -j 4 bin_PROGRAMS=@; s@^make install$@make install bin_PROGRAMS=@' /work/build.sh "
            "&& chmod +x /work/build.sh && /work/build.sh",
            1,
        )
    if project.name == "libmediainfo":
        # CMake cannot discover clang-scan-deps through the AFL++ compiler
        # wrapper when MediaInfoLib auto-selects C++26. The library supports
        # C++17, which avoids module dependency scanning.
        text = text.replace(
            "&& chmod +x /work/build.sh && /work/build.sh",
            "&& sed -i 's@-DCMAKE_BUILD_TYPE=Release @-DCMAKE_BUILD_TYPE=Release -DCMAKE_CXX_STANDARD=17 @' /work/build.sh "
            "&& chmod +x /work/build.sh && /work/build.sh",
            1,
        )
    if project.name in {"gstreamer", "sfml", "csfml", "taglib", "id3lib", "libmp3splt", "mupdf", "qpdf"}:
        # Build shared parser libraries with AFL++ before linking the harness.
        # The source build remains a reusable Docker layer.
        source_rewrite = (
            "RUN python3 -c 'from pathlib import Path; p=Path(\"/work/build-source.sh\"); "
            "s=p.read_text().replace(\"clang++\",\"AFL_CXX\")"
            ".replace(\"clang\",\"afl-clang-fast\")"
            ".replace(\"AFL_CXX\",\"afl-clang-fast++\"); p.write_text(s)' "
            "&& chmod +x /work/build-source.sh && /work/build-source.sh"
        )
        text = text.replace(
            "RUN chmod +x /work/build-source.sh && /work/build-source.sh",
            source_rewrite,
            1,
        )
        if project.name == "csfml":
            csfml_rewrite = source_rewrite.replace("build-source.sh", "build-csfml.sh")
            text = text.replace(
                "RUN chmod +x /work/build-csfml.sh && /work/build-csfml.sh",
                csfml_rewrite,
                1,
            )
    if project.name == "gstreamer":
        plugins = (
            "app", "audioconvert", "audioparsers", "coreelements",
            "id3demux", "isomp4", "playback", "pnm", "typefindfunctions",
            "wavparse",
        )
        if project.parent.parent.name in {"mp4", "mp3_id3v2"}:
            plugins += ("libav",)
        text += "\nENV AFL_PRELOAD=" + ":".join(
            f"/work/install/lib/gstreamer-1.0/libgst{name}.so"
            for name in plugins
        ) + "\n"
    if project.name == "imlib2":
        loader = {"png": "png", "ascii_pnm": "pnm", "svg": "svg"}[project.parent.parent.name]
        text += f"\nENV AFL_PRELOAD=/work/install/lib/imlib2/loaders/{loader}.so\n"
    if project.name == "libmp3splt":
        text += "\nENV AFL_PRELOAD=/work/install/lib/libmp3splt0/libsplt_mp3.so\n"
    return "# AFL++ overlay generated by scripts/build_afl_native.py\n" + text


def command(args: list[str]) -> str:
    result = subprocess.run(args, cwd=ROOT, capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(f"{' '.join(args)} failed:\n{result.stderr[-4000:]}")
    return result.stdout.strip()


def build_one(format_name: str, ecosystem: str, slug: str) -> dict:
    if ecosystem not in {"c", "cpp"}:
        raise ValueError("AFL++ source overlay currently supports C and C++")
    project, manifest = project_for(format_name, ecosystem, slug)
    overlay = OVERLAYS / format_name / ecosystem / slug
    overlay.mkdir(parents=True, exist_ok=True)
    dockerfile = overlay / "Dockerfile"
    dockerfile.write_text(derived_dockerfile(project))
    image = f"parsarium-afl/{format_name}-{ecosystem}-{slug}:local"
    entrypoint = manifest.get("afl_entrypoint", "/work/fuzzer")
    print(f"Building {image}", flush=True)
    with docker_build_slot():
        command(["docker", "build", "--quiet", "--platform", manifest["platform"],
                 "-f", str(dockerfile), "-t", image, str(project)])
    image_id = command(["docker", "image", "inspect", image, "--format", "{{.Id}}"])
    tool_version = command(["docker", "run", "--rm", "--platform", manifest["platform"],
                            "--entrypoint", "dpkg-query", image,
                            "-W", "-f=${Version}", "afl++"])
    image_env = json.loads(command(["docker", "image", "inspect", image,
                                    "--format", "{{json .Config.Env}}"]))
    preload = next((item.partition("=")[2] for item in image_env
                    if item.startswith("AFL_PRELOAD=")), None)
    probe_env = ["-e", "AFL_DUMP_MAP_SIZE=1"]
    if preload:
        probe_env += ["-e", f"LD_PRELOAD={preload}"]
    map_probe = subprocess.run(["docker", "run", "--rm", "--platform", manifest["platform"],
                            *probe_env, "--entrypoint", entrypoint, image],
                               cwd=ROOT, capture_output=True, text=True)
    if not map_probe.stdout.strip().isdigit():
        raise RuntimeError(f"AFL++ map size probe failed: {map_probe.stderr[-2000:]}")
    map_size = int(map_probe.stdout.strip())
    control = ROOT / manifest["control"]
    edges = overlay / "edges.txt"
    showmap = subprocess.run([
        "docker", "run", "--rm", "--platform", manifest["platform"],
        "--network", "none", "--read-only", "--cap-drop", "ALL",
        "--security-opt", "no-new-privileges", "--user", f"{os.getuid()}:{os.getgid()}",
        "--tmpfs", "/tmp:rw,exec,nosuid,size=64m", "--workdir", "/tmp",
        "-e", f"AFL_MAP_SIZE={map_size}",
        "-v", f"{control}:/input/control:ro", "-v", f"{overlay}:/coverage",
        "--entrypoint", "afl-showmap", image,
        "-m", "none", "-t", "10000", "-o", "/coverage/edges.txt", "--",
        entrypoint, "/input/control",
    ], cwd=ROOT, capture_output=True, text=True)
    if showmap.returncode:
        raise RuntimeError(f"afl-showmap failed: {(showmap.stdout + showmap.stderr)[-4000:]}")
    edge_count = sum(1 for line in edges.read_text().splitlines() if line)
    if edge_count == 0:
        raise RuntimeError("AFL++ reported no feedback edges on the valid control")
    edges.unlink()
    receipt = {"schema_version": 1, "project": str(project.relative_to(ROOT / "projects")),
               "base_project_receipt_sha256": sha256((project / "verification.json").read_bytes()).hexdigest(),
               "overlay_dockerfile_sha256": sha256(dockerfile.read_bytes()).hexdigest(),
               "afl_package": AFL_PACKAGE, "afl_version_output": tool_version,
               "image_id": image_id, "platform": manifest["platform"],
               "control_sha256": manifest["control_sha256"],
               "feedback_edges": edge_count, "afl_map_size": map_size, "pass": True}
    (overlay / "verification.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(f"Verified {format_name}/{ecosystem}/{slug}: {edge_count} AFL++ feedback edges")
    return receipt


def main() -> None:
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("format", nargs="?")
    cli.add_argument("ecosystem", nargs="?")
    cli.add_argument("package_slug", nargs="?")
    cli.add_argument("--all", action="store_true", help="build and smoke all C/C++ overlays")
    cli.add_argument("--workers", type=int, default=2)
    args = cli.parse_args()
    if not args.all:
        if not all((args.format, args.ecosystem, args.package_slug)):
            cli.error("provide format, ecosystem, and package slug or use --all")
        build_one(args.format, args.ecosystem, args.package_slug)
        return
    if args.workers < 1:
        cli.error("workers must be positive")
    paths = sorted(path for path in (ROOT / "projects").glob("*/*/*/manifest.json")
                   if path.parent.parent.name in {"c", "cpp"})
    records = []
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        tasks = {pool.submit(build_one, *path.parent.relative_to(ROOT / "projects").parts): path
                 for path in paths}
        for future in as_completed(tasks):
            path = tasks[future]
            project = str(path.parent.relative_to(ROOT / "projects"))
            try:
                receipt = future.result()
                records.append({"project": project, "status": "verified",
                                "feedback_edges": receipt["feedback_edges"],
                                "image_id": receipt["image_id"]})
            except Exception as exc:
                records.append({"project": project, "status": "failed", "error": str(exc)[-4000:]})
                print(f"FAILED {project}: {exc}", flush=True)
    records.sort(key=lambda item: item["project"])
    report = {"schema_version": 1, "checked_at_utc": datetime.now(timezone.utc).isoformat(),
              "afl_package": AFL_PACKAGE, "projects_total": len(records),
              "projects_verified": sum(item["status"] == "verified" for item in records),
              "results": records}
    (ROOT / "data/afl-native-smoke.json").write_text(json.dumps(report, indent=2) + "\n")
    print(f"{report['projects_verified']}/{report['projects_total']} AFL++ overlays verified")
    if report["projects_verified"] != report["projects_total"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
